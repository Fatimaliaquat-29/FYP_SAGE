MP_PAIRS = [(11, 12), (23, 24), (11, 23), (12, 24), (23, 25), (25, 27), (24, 26), (26, 28)]

OVERLAY_CLIPS = {
    "lying": "S0807_Floor_long_lie",
    "low_light": "H0730_Bend_pickup_lowLight",
    "occluded_legs": "H0730_Sit_Stand_AnklesInvisible",
}


def _draw_skeleton(frame: np.ndarray, row: dict, color: Tuple[int, int, int], radius: int = 5) -> None:
    h, w = frame.shape[:2]
    pts = {}
    for i in range(33):
        x, y = row.get(f"lm_{i}_x"), row.get(f"lm_{i}_y")
        if x is None or y is None or (isinstance(x, float) and np.isnan(x)) or (isinstance(y, float) and np.isnan(y)):
            continue
        pts[i] = (int(round(x * w)), int(round(y * h)))
    for i, (px, py) in pts.items():
        cv2.circle(frame, (px, py), radius, color, -1)
    for a, b in MP_PAIRS:
        if a in pts and b in pts:
            cv2.line(frame, pts[a], pts[b], color, 2)


def _frame_at(video_path: str, frame_number: int) -> Optional[np.ndarray]:
    cap = cv2.VideoCapture(video_path)
    cap.set(cv2.CAP_PROP_POS_FRAMES, frame_number - 1)
    ret, frame = cap.read()
    cap.release()
    return frame if ret else None


def generate_overlays(clips_registry: Dict[str, dict]) -> List[str]:
    written = []
    for category, clip_id in OVERLAY_CLIPS.items():
        mp_cache = CACHE_DIR / f"{clip_id}__mediapipe.pkl"
        yolo_cache = CACHE_DIR / f"{clip_id}__yolo26n-pose_raw_cuda0.pkl"
        if clip_id not in clips_registry or not mp_cache.exists() or not yolo_cache.exists():
            print(f"  [overlays] SKIP {category} ({clip_id}): cache missing "
                  f"(mp={mp_cache.exists()}, yolo={yolo_cache.exists()})")
            continue

        with open(mp_cache, "rb") as f:
            mp_data = pickle.load(f)
        with open(yolo_cache, "rb") as f:
            yolo_data = pickle.load(f)

        mp_rows = mp_data["rows"]
        yolo_rows, _person_counts = _apply_threshold_and_remap(yolo_data["frames_raw"], 0.5)

        total = min(len(mp_rows), len(yolo_rows))
        sample_frames = sorted(set(int(total * f) for f in (0.2, 0.5, 0.8)))
        sample_frames = [f for f in sample_frames if 0 <= f < total][:2]  # 2 frames per clip -> 6 total

        video_path = clips_registry[clip_id]["video_path"]
        for idx in sample_frames:
            fn = mp_rows[idx]["frame_number"]
            frame = _frame_at(video_path, fn)
            if frame is None:
                continue
            mp_frame = frame.copy()
            yolo_frame = frame.copy()
            _draw_skeleton(mp_frame, mp_rows[idx], (0, 255, 0))
            _draw_skeleton(yolo_frame, yolo_rows[idx], (0, 128, 255))
            combined = np.hstack([mp_frame, yolo_frame])
            cv2.putText(combined, "MediaPipe", (10, 30), cv2.FONT_HERSHEY_SIMPLEX, 1, (0, 255, 0), 2)
            cv2.putText(combined, "YOLO26", (frame.shape[1] + 10, 30), cv2.FONT_HERSHEY_SIMPLEX, 1, (0, 128, 255), 2)
            out_path = OVERLAY_DIR / f"{category}_{clip_id}_frame{fn}.png"
            cv2.imwrite(str(out_path), combined)
            written.append(str(out_path.relative_to(BENCH_DIR)))
            print(f"  [overlays] wrote {out_path.name}")
    return written


