# 3. Coordinate sanity: range + left/right not swapped
# ------------------------------------------------------------------------------

def check_coordinate_sanity(clip_ids: List[str]) -> dict:
    n_checked = 0
    n_out_of_range = 0
    n_lr_compared = 0
    n_lr_disagree = 0

    for clip_id in clip_ids:
        mp_cache = CACHE_DIR / f"{clip_id}__mediapipe.pkl"
        yolo_cache = CACHE_DIR / f"{clip_id}__yolo26n-pose_raw_cuda0.pkl"
        if not mp_cache.exists() or not yolo_cache.exists():
            continue
        with open(mp_cache, "rb") as f:
            mp_rows = pickle.load(f)["rows"]
        with open(yolo_cache, "rb") as f:
            yolo_raw = pickle.load(f)["frames_raw"]
        yolo_rows, _ = _apply_threshold_and_remap(yolo_raw, 0.5)

        for r in yolo_rows:
            for i in range(33):
                x, y = r.get(f"lm_{i}_x"), r.get(f"lm_{i}_y")
                if x is None or (isinstance(x, float) and np.isnan(x)):
                    continue
                n_checked += 1
                if not (-0.05 <= x <= 1.05 and -0.05 <= y <= 1.05):
                    n_out_of_range += 1

        for mp_r, y_r in zip(mp_rows, yolo_rows):
            mp_l, mp_rt = mp_r.get("lm_11_x"), mp_r.get("lm_12_x")
            y_l, y_rt = y_r.get("lm_11_x"), y_r.get("lm_12_x")
            if any(v is None or (isinstance(v, float) and np.isnan(v)) for v in (mp_l, mp_rt, y_l, y_rt)):
                continue
            mp_sign = mp_l - mp_rt
            y_sign = y_l - y_rt
            if abs(mp_sign) < 0.02 or abs(y_sign) < 0.02:
                continue  # too close together to be a meaningful L/R check this frame
            n_lr_compared += 1
            if (mp_sign > 0) != (y_sign > 0):
                n_lr_disagree += 1

    return {
        "n_coords_checked": n_checked,
        "n_out_of_range": n_out_of_range,
        "n_lr_frames_compared": n_lr_compared,
        "n_lr_disagreements": n_lr_disagree,
    }


