def main():
    sys.path.insert(0, str(BENCH_DIR))
    from benchmark_pose import discover_all_clips  # noqa: E402

    clips, _skipped = discover_all_clips()

    print("=== 1. Baseline reproduction ===")
    repro = reproduce_baseline(clips)
    for r in repro:
        print(f"  {r['clip_id']:30s} {r['status']}")

    print("\n=== 2. Overlays ===")
    overlays = generate_overlays(clips)

    print("\n=== 3. Coordinate sanity ===")
    coord = check_coordinate_sanity(sorted(clips.keys()))
    print(json.dumps(coord, indent=2))

    out = {
        "baseline_reproduction": repro,
        "overlays": overlays,
        "coordinate_sanity": coord,
        "historical_unreproducible": HISTORICAL_UNREPRODUCIBLE,
    }
    out_path = RESULTS_DIR / "sanity_checks.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=2)
    print(f"\nWrote {out_path}")


if __name__ == "__main__":
    main()
