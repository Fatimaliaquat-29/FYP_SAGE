"""
sanity_checks.py
=================
Step-4 sanity checks for the YOLO26-pose vs MediaPipe benchmark:

  1. Baseline reproduction: run the (cached) MediaPipe backend through THIS
     harness and compare its per-clip posture accuracy + fall result against
     historical results already committed under results/. Those files were
     generated by evaluate_real_footage.py itself (unmodified, same function
     we reuse), at various points in the project's history, so this checks
     that our harness wires classify_frames/score_posture/score_fall together
     the same way evaluate_real_footage.py's own evaluate_clip() does -- not
     that the heuristic itself hasn't changed over time (it has; see
     pipeline_utils.py's version history comments).

  2. Visual overlay: MediaPipe skeleton vs YOLO skeleton side-by-side PNGs for
     6 frames spanning a lying clip, a low-light clip, and an occluded-legs
     clip.

  3. Coordinate sanity: x,y in [0,1] (with MediaPipe's own small extrapolation
     margin) and left/right not swapped, checked across many cached frames,
     not just eyeballed.

Reads only from cache/ (populated by benchmark_pose.py) and results/
(read-only, historical reference). Writes only under
benchmarks/pose_yolo26/results/.
"""

