def _fmt_fall_from_metrics(fall_result: dict) -> str:
    r = fall_result["result"]
    if r == "true_positive":
        return f"TP (latency {fall_result['latency']} frames)"
    if r == "false_negative":
        return "FN"
    if r == "false_positive":
        fps_str = ", ".join(str(f) for f in fall_result["fp_frames"][:5])
        return f"FP frames [{fps_str}]"
    return "-"


def reproduce_baseline(clips_registry: Dict[str, dict]) -> List[dict]:
    """For every clip with a historical reference AND a mediapipe cache
    entry, recompute accuracy/fall via THIS harness and diff against the
    historical number."""
    rows = []
    for clip_id, ref in HISTORICAL_REFERENCE.items():
        cache_path = CACHE_DIR / f"{clip_id}__mediapipe.pkl"
        if not cache_path.exists() or clip_id not in clips_registry:
            rows.append({"clip_id": clip_id, "status": "no cached mediapipe run yet", **ref})
            continue

        with open(cache_path, "rb") as f:
            cached = pickle.load(f)
        info = clips_registry[clip_id]

        gt_df = load_ground_truth(info["gt_path"])
        frame_gt = build_frame_gt(gt_df, cached["fps"], cached["total_frames"])
        fall_window = get_fall_window(gt_df, cached["fps"])

        classified = classify_frames(cached["rows"], clip_name=clip_id)
        accuracy, confusion, _ = score_posture(classified, frame_gt)
        fall_result = score_fall(classified, fall_window)
        fall_str = _fmt_fall_from_metrics(fall_result)

        acc_match = abs(accuracy - ref["accuracy"]) < 0.5
        fall_match = fall_str.split(" ")[0] == ref["fall"].split(" ")[0]  # TP/FN/FP/- match, ignore exact latency

        rows.append({
            "clip_id": clip_id,
            "status": "OK" if (acc_match and fall_match) else "MISMATCH",
            "accuracy_now": round(accuracy, 1),
            "accuracy_ref": ref["accuracy"],
            "fall_now": fall_str,
            "fall_ref": ref["fall"],
            "source": ref["source"],
        })
    return rows


